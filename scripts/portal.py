# exact-commit links

def checkpoint_lines(results, manifest, refresh: bool):
    """Line numbers of registry declarations at the pinned checkpoint. Recomputed from
    git when the checkpoint is available locally; otherwise the committed file is used
    (shallow CI clones do not contain the checkpoint)."""
    path = ROOT / "docs/data/checkpoint.json"
    stored = json.loads(path.read_text()) if path.exists() else {"commit": CHECKPOINT, "lines": {}}
    if not refresh:
        return stored
    have = subprocess.run(["git", "cat-file", "-e", f"{CHECKPOINT}^{{commit}}"], cwd=ROOT,
                          capture_output=True).returncode == 0
    if not have:
        return stored
    lines = {}
    cache = {}
    for r in results:
        for name in r.get("lean", []):
            e = resolve(name, manifest)
            if not e:
                continue
            f = e["file"]
            if f not in cache:
                out = subprocess.run(["git", "show", f"{CHECKPOINT}:{f}"], cwd=ROOT, capture_output=True, text=True)
                cache[f] = out.stdout.splitlines() if out.returncode == 0 else None
            src = cache[f]
            if src is None:
                continue
            pat = re.compile(rf"^\s*(?:@\[[^\]]*\]\s*)?(?:protected\s+)?(theorem|lemma)\s+{re.escape(e['label'])}\b")
            hits = [i for i, l in enumerate(src, 1) if pat.match(l)]
            if len(hits) == 1:
                lines[name] = [f, hits[0]]
    return {"commit": CHECKPOINT, "lines": dict(sorted(lines.items()))}


# ---------------------------------------------------------------------------
# rendering helpers

def anchor(rid: str) -> str:
    return rid.lower()


def rel(target: str, frm: str) -> str:
    """Relative link from the directory of ``frm`` to repository path ``target``."""
    depth = frm.count("/")
    return "../" * depth + target


def decl_link(e, frm):
    return f"[`{e['label']}`]({rel(e['file'], frm)}#L{e['line']})"


def path_link(target, frm, label=None):
    file, _, frag = target.partition("#")
    name = label or nice_name(target)
    return f"[{name}]({rel(file, frm)}{'#' + frag if frag else ''})"


def nice_name(target):
    file, _, frag = target.partition("#")
    base = pathlib.PurePosixPath(file).name
    if frag:
        return f"{base} § {frag.replace('-', ' ')}"
    return base


def first_sentence(doc: str, limit=160) -> str:
    doc = " ".join(doc.split())
    if not doc:
        return ""
    m = re.match(r"(.+?[.!?])(\s|$)", doc)
    s = m.group(1) if m else doc
    if len(s) > limit:
        s = s[: limit - 1].rsplit(" ", 1)[0] + "…"
    return s.replace("|", "\\|")


def paper_of(rid, papers):
    fam = rid[:2]
    for p in papers:
        if fam in p["families"]:
            return p
    return None


