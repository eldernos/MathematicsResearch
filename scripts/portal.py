def build_papers_block(papers):
    frm = "README.md"
    label = {"draft": "Draft", "planned": "Planned", "internally reviewed": "Internally reviewed",
             "external review": "Under external review", "published": "Published"}
    rows = ["| | Manuscript | Results | Status | Files |", "| --- | --- | --- | --- | --- |"]
    for p in papers:
        ids = " ".join(f"[{x}](docs/results.md#{anchor(x)})" for x in p["principal"])
        d = p["dir"]
        files = (f"[PDF]({d}/paper.pdf) · [LaTeX]({d}/paper.tex) · [References]({d}/references.bib) · "
                 f"[Reviewer guide]({d}/REVIEW.md)")
        rows.append(f"| {p['number']} | **{p['title']}** | {ids} | {label[p['status']]} | {files} |")
    abstracts = ["<details>\n<summary>Abstracts</summary>\n"]
    for p in papers:
        abstracts.append(f"**{p['number']}. {p['title']}.** " + " ".join(p["abstract"].split()) + "\n")
    abstracts.append("</details>")
    return "\n".join(rows) + "\n\n" + "\n".join(abstracts)


def embedded_figure(f, frm):
    short = f.get("summary") or first_sentence(f["caption"], limit=400).replace("\\|", "|")
    return (f'<p align="center">\n{picture(f, frm, width=640)}\n</p>\n\n'
            f'<sub>Figure {f["number"]}. {short} [Caption, data and generator]({rel("docs/figures.md", frm)}#{f["slug"]})</sub>')


def replace_block(text, name, body):
    pattern = re.compile(rf"(<!-- BEGIN {re.escape(name)} -->\n)(.*?)(\n?<!-- END {re.escape(name)} -->)", re.S)
    m = pattern.search(text)
    if not m:
        return text
    return text[: m.start()] + m.group(1) + body + "\n" + f"<!-- END {name} -->" + text[m.end():]


