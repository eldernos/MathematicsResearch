def slug(heading: str) -> str:
    """GitHub's heading anchor: strip markup, lowercase, keep letters, digits, spaces,
    hyphens and underscores, and turn spaces into hyphens."""
    h = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)  # links -> text
    h = re.sub(r"<[^>]+>", "", h)
    h = h.replace("`", "").replace("*", "").replace("$", "")
    h = h.strip().lower()
    out = []
    for ch in h:
        cat = unicodedata.category(ch)
        if ch in " -_" or cat[0] in "LN" or cat == "Mn":
            out.append("-" if ch == " " else ch)
    return "".join(out)


def anchors_of(path: pathlib.Path, cache={}):
    if path in cache:
        return cache[path]
    text = path.read_text()
    found, counts = set(), defaultdict(int)
    in_code = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:
            s = slug(m.group(2))
            n = counts[s]
            counts[s] += 1
            found.add(s if n == 0 else f"{s}-{n}")
    for m in re.finditer(r'<a\s+(?:id|name)="([^"]+)"', text):
        found.add(m.group(1).lower())
    cache[path] = found
    return found


LINK_RE = re.compile(r"(?<!\!)\[(?:[^\[\]]|\[[^\]]*\])*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)|(?:src|srcset|href)=\"([^\"]+)\"")


def markdown_files():
    files = [ROOT / "README.md", ROOT / "CONTRIBUTING.md"]
    files += sorted((ROOT / "docs").rglob("*.md"))
    files += sorted((ROOT / "notes").glob("*.md"))
    for phase in ("phase18", "phase19"):
        files += sorted((ROOT / "notes" / phase).rglob("*.md"))
    files += sorted((ROOT / "papers").rglob("*.md")) if (ROOT / "papers").exists() else []
    files += sorted((ROOT / ".github").rglob("*.md")) if (ROOT / ".github").exists() else []
    return [f for f in files if f.exists()]


def check_links(errors, warnings, strict):
    for md in markdown_files():
        text = md.read_text()
        # ignore fenced code blocks
        text = re.sub(r"```.*?```", "", text, flags=re.S)
        for m in LINK_RE.finditer(text):
            target = m.group(1) or m.group(2)
            if re.match(r"^[a-z]+:", target) or target.startswith("//"):
                continue
            where = md.relative_to(ROOT).as_posix()
            file, _, frag = target.partition("#")
            file = unquote(file)
            dest = (md.parent / file).resolve() if file else md
            try:
                dest.relative_to(ROOT)
            except ValueError:
                errors.append(f"{where}: link leaves the repository: {target}")
                continue
            if not dest.exists():
                msg = f"{where}: missing target {target}"
                inside_papers = dest.relative_to(ROOT).parts[:1] == ("papers",)
                (errors if strict or not inside_papers else warnings).append(msg)
                continue
            if not frag:
                continue
            if re.fullmatch(r"L\d+(-L\d+)?", frag):
                n = len(dest.read_text().splitlines())
                lines = [int(x) for x in re.findall(r"\d+", frag)]
                if max(lines) > n:
                    errors.append(f"{where}: line anchor beyond end of file: {target}")
                continue
            if dest.suffix == ".md" and frag.lower() not in anchors_of(dest):
                errors.append(f"{where}: missing anchor #{frag} in {dest.relative_to(ROOT)}")


def check_registry(errors, warnings):
    manifest, entries = load_manifest()
    results, papers = load_registry()
    figures = {f["slug"] for f in load_figures()}
    ids = {}
    for r in results:
        where = f"{r.get('_file')}:{r.get('id', '?')}"
        for k in REQUIRED:
            if not r.get(k):
                errors.append(f"{where}: missing field {k}")
        rid = r.get("id", "")
        if not ID_RE.fullmatch(rid):
            errors.append(f"{where}: malformed identifier")
            continue
        if pathlib.Path(r["_file"]).stem != rid[:2]:
            errors.append(f"{where}: identifier prefix does not match file")
        if rid in ids:
            errors.append(f"{where}: duplicate identifier")
        ids[rid] = r
        if r.get("topic") not in TOPICS:
            errors.append(f"{where}: unknown topic {r.get('topic')!r}")
        if r.get("status") not in STATUS:
            errors.append(f"{where}: unknown status {r.get('status')!r}")
        if r.get("status") in ("lean", "lean+paper") and not r.get("lean"):
            errors.append(f"{where}: status {r['status']} requires Lean declarations")
        if r.get("status") == "lean+paper" and not (r.get("inputs") or "deduction" in r.get("scope", "").lower()):
            warnings.append(f"{where}: lean+paper without `inputs`")
        for n in r.get("lean", []):
            e = resolve(n, manifest)
            if not e:
                errors.append(f"{where}: unknown Lean declaration {n}")
            elif e.get("_unindexed"):
                warnings.append(f"{where}: {n} found at {e['file']}:{e['line']} but not in the manifest "
                                "(module not imported by NormalityChecker.lean?)")
        for s in r.get("supersedes", []):
            if not ID_RE.fullmatch(s) and not resolve(s, manifest):
                errors.append(f"{where}: unknown superseded declaration {s}")
        for t in r.get("proof", []) + ([r["computation"]] if isinstance(r.get("computation"), str) else r.get("computation", [])):
            f = t.partition("#")[0]
            if f and "/" in f and not (ROOT / f).exists():
                errors.append(f"{where}: missing file {t}")
        for s in r.get("figures", []):
            if s not in figures:
                errors.append(f"{where}: unknown figure {s}")
        for text_field in ("statement", "scope"):
            bad = re.findall(r"\\(?:operatorname|substack|text|mathrm\{[^}]*\}\s*\\|begin|newcommand|def)\b",
                             r.get(text_field, ""))
            if bad:
                errors.append(f"{where}: {text_field} uses discouraged TeX {sorted(set(bad))}")
    for r in results:
        for x in r.get("related", []) + [s for s in r.get("supersedes", []) if ID_RE.fullmatch(s)]:
            if x not in ids:
                errors.append(f"{r['_file']}:{r['id']}: refers to unknown identifier {x}")
    # principal results must be covered by an axiom audit (Audit.lean or a paper check file)
    audited = (ROOT / "Audit.lean").read_text()
    for chk in list((ROOT / "papers").glob("*/[Cc]heck.lean")) if (ROOT / "papers").exists() else []:
        audited += chk.read_text()
    for r in results:
        if r.get("principal") and r.get("lean"):
            label = r["lean"][0].rsplit(".", 1)[-1]
            if not re.search(rf"\b{re.escape(label)}\b", audited):
                warnings.append(f"{r['_file']}:{r['id']}: main declaration {r['lean'][0]} is not in Audit.lean "
                                "or a paper check file")
    # consecutive numbering per family
    fam = defaultdict(list)
    for rid in ids:
        fam[rid[:2]].append(int(rid[3:]))
    for f, nums in fam.items():
        if sorted(nums) != list(range(1, len(nums) + 1)):
            warnings.append(f"{f}: identifiers are not consecutive: {sorted(nums)}")
    for p in papers:
        if p.get("status") not in PAPER_STATUS:
            errors.append(f"papers.toml: {p.get('number')}: status must be one of {PAPER_STATUS}")
        for x in p.get("principal", []):
            if x not in ids:
                errors.append(f"papers.toml: {p['number']}: unknown identifier {x}")
        for word in ("peer reviewed", "peer-reviewed", "accepted"):
            if word in p.get("abstract", "").lower():
                errors.append(f"papers.toml: {p['number']}: abstract claims '{word}'")
    return ids


def check_id_mentions(ids, errors):
    for md in markdown_files():
        if md.is_relative_to(ROOT / "docs/registry"):
            continue
        for m in ID_RE.finditer(md.read_text()):
            if m.group(0) not in ids:
                errors.append(f"{md.relative_to(ROOT)}: mentions unknown result {m.group(0)}")


def check_topics(errors):
    _, entries = load_manifest()
    topics = load_topics()
    assigned = defaultdict(list)
    for key, t in topics.items():
        for m in t["modules"]:
            assigned[m].append(key)
    modules = {e["file"][len("NormalityChecker/"):-len(".lean")] for e in entries}
    for m in sorted(modules):
        if len(assigned.get(m, [])) != 1:
            errors.append(f"docs/data/topics.toml: module {m} has topics {assigned.get(m, [])}")
    for m in sorted(set(assigned) - modules):
        if not (ROOT / f"NormalityChecker/{m}.lean").exists():
            errors.append(f"docs/data/topics.toml: no such module {m}")


def check_figures(errors):
    out = subprocess.run([sys.executable, "-B", str(ROOT / "scripts/figures/build.py"), "--check"],
                         capture_output=True, text=True)
    if out.returncode != 0:
        errors.extend("figures: " + l for l in out.stdout.strip().splitlines() if l and "current" not in l)


def check_figure_sources(errors):
    manifest, _ = load_manifest()
    for f in load_figures():
        for src in f.get("sources", []):
            if src.startswith("NormalityChecker."):
                if src in manifest or source_lookup(src):
                    continue
                label = src.rsplit(".", 1)[-1]
                pat = re.compile(rf"^\s*(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+)?(?:def|abbrev|structure)\s+{re.escape(label)}\b", re.M)
                if not any(pat.search(p.read_text()) for p in (ROOT / "NormalityChecker").rglob("*.lean")):
                    errors.append(f"figures: {f['slug']} cites unknown declaration {src}")
            elif not (ROOT / src.partition("#")[0]).exists():
                errors.append(f"figures: {f['slug']} cites missing file {src}")
        for rid in f.get("results", []):
            if not ID_RE.fullmatch(rid):
                errors.append(f"figures: {f['slug']} has malformed result {rid}")


def check_readme_figures(errors):
    readme = (ROOT / "README.md").read_text()
    for m in re.finditer(r'<img src="([^"]+)"([^>]*)>', readme):
        if 'alt="' not in m.group(2) or 'alt=""' in m.group(2):
            errors.append(f"README.md: image without alternative text: {m.group(1)}")


def cmd_check(args):
    errors, warnings = [], []
    files = derived(False)
    for path, text in files.items():
        p = ROOT / path
        if not p.exists() or p.read_text() != text:
            errors.append(f"{path} is stale. Run python3 scripts/portal.py build")
    ids = check_registry(errors, warnings)
    check_id_mentions(ids, errors)
    check_topics(errors)
    check_links(errors, warnings, args.strict)
    check_readme_figures(errors)
    check_figure_sources(errors)
    if not args.skip_figures:
        check_figures(errors)
    pending = sorted({w.split("missing target ", 1)[1].lstrip("./") for w in warnings if "missing target" in w})
    for w in warnings:
        if "missing target" not in w:
            print(f"warning: {w}")
    if pending:
        print(f"warning: {len(pending)} manuscript paths are linked but not yet present "
              f"(--strict makes this an error): {', '.join(pending)}")
    for e in errors:
        print(f"error: {e}")
    if errors:
        return 1
    print(f"Portal verified: {len(ids)} registered results, {len(markdown_files())} Markdown files, "
          f"links, anchors, identifiers, topics and figures.")
    return 0


def cmd_link(args):
    manifest, _ = load_manifest()
    results, _ = load_registry()
    r = next((x for x in results if x["id"] == args.id), None)
    if not r:
        print(f"unknown identifier {args.id}")
        return 1
    commit = args.commit or subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                                           text=True).stdout.strip()
    print(f"{r['id']} · {r['title']}")
    for n in r.get("lean", []):
        e = resolve(n, manifest)
        print(f"  {n}\n    {REPO}/blob/{commit}/{e['file']}#L{e['line']}")
    print(f"  registry: {REPO}/blob/{commit}/docs/results.md#{anchor(r['id'])}")
    print("  (line numbers are taken from the current checkout; pass the commit that contains them)")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    c = sub.add_parser("check")
    c.add_argument("--strict", action="store_true", help="fail on missing manuscript files")
    c.add_argument("--skip-figures", action="store_true")
    l = sub.add_parser("link")
    l.add_argument("id")
    l.add_argument("--commit")
    args = ap.parse_args(argv)
    return {"build": cmd_build, "check": cmd_check, "link": cmd_link}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
