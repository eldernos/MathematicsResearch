def build_theorems(entries, topics, results):
    frm = "docs/theorems.md"
    by_module = defaultdict(list)
    for e in entries:
        by_module[e["file"][len("NormalityChecker/"):-len(".lean")]].append(e)
    used_by = defaultdict(list)
    for r in results:
        for n in r.get("lean", []):
            used_by[n].append(r["id"])
    out = [GENERATED_NOTE.format(src="docs/data/declarations.json and docs/data/topics.toml"),
           "# Complete declaration directory\n",
           f"Every named public theorem and lemma of the Lean library, {len(entries)} in all, grouped by "
           "mathematical topic and then by module. Each name links to its source line. The summary is the first "
           "sentence of the docstring; the Lean statement is authoritative. Result identifiers mark declarations "
           "cited in the [curated index](results.md). The machine-readable manifest is "
           "[declarations.json](data/declarations.json). The same list, by module only, is collapsed at the end "
           "of the [README](../README.md#complete-declaration-directory).\n",
           "Declaration counts describe the size of the library, not the mathematical significance of its results.\n"]
    toc = []
    for key, t in topics.items():
        n = sum(len(by_module.get(m, [])) for m in t["modules"])
        toc.append(f"- [{t['title']}](#{slug(t['title'])}) · {n} declarations")
    out.append("\n".join(toc) + "\n")
    for key, t in topics.items():
        out.append(f"## {t['title']}\n")
        for m in sorted(t["modules"], key=str.lower):
            items = by_module.get(m)
            if not items:
                continue
            out.append(f"### {m}\n")
            out.append(f"[`NormalityChecker/{m}.lean`]({rel(f'NormalityChecker/{m}.lean', frm)})\n")
            out.append("| Declaration | Summary |\n| --- | --- |")
            for e in items:
                ids = " ".join(f"[{i}](results.md#{anchor(i)})" for i in used_by.get(e["name"], []))
                tag = f" {ids}" if ids else ""
                out.append(f"| [`{e['name'].removeprefix('NormalityChecker.')}`]({rel(e['file'], frm)}#L{e['line']})"
                           f"{tag} | {first_sentence(e['doc'])} |")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


