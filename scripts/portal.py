def picture(fig, frm, width=None):
    w = f' width="{width}"' if width else ""
    alt = fig["alt"].replace('"', "&quot;")
    return (f'<picture>\n  <source media="(prefers-color-scheme: dark)" srcset="{rel(fig["dark"], frm)}">\n'
            f'  <img src="{rel(fig["light"], frm)}" alt="{alt}"{w}>\n</picture>')


def build_figures(figures):
    frm = "docs/figures.md"
    prov = {"theorem": "Theorem consequence", "exact": "Exact finite computation",
            "illustration": "Numerical illustration, not evidence"}
    out = [GENERATED_NOTE.format(src="assets/figures/figures.json"),
           "# Figures\n",
           "Each figure is generated, together with its data, by a standard-library Python script. "
           "Run `python3 scripts/figures/build.py` to regenerate all of them and `--check` to verify the committed "
           "files. Every figure carries a provenance label: a *theorem consequence* shows values implied by a "
           "stated theorem, an *exact finite computation* uses rational arithmetic on a finite range, and a "
           "*numerical illustration* is a finite sample that is not evidence for any limit statement.\n",
           "**Colour convention.** Aqua marks normality and uniform distribution. Orange marks resonance, "
           "concentration and exact positive discrepancy. Violet marks an arithmetic barrier. Grey hatching marks "
           "unresolved conditions. Blue is used for neutral exact data. Pages switch between light and dark "
           "variants automatically. Light-theme PDFs for manuscripts are in [assets/figures/pdf](../assets/figures/pdf).\n"]
    out.append("\n".join(f"{f['number']}. [{f['title']}](#{f['slug']})" for f in figures) + "\n")
    for f in figures:
        out.append(f'<a id="{f["slug"]}"></a>\n')
        out.append(f"## Figure {f['number']}. {f['title']}\n")
        out.append(picture(f, frm) + "\n")
        out.append(f"**{prov[f['provenance']]}.** " + " ".join(f["caption"].split()) + "\n")
        res = " · ".join(f"[{r}](results.md#{anchor(r)})" for r in f["results"])
        files = [f"[light SVG]({rel(f['light'], frm)})", f"[dark SVG]({rel(f['dark'], frm)})",
                 f"[PDF]({rel(f['pdf'], frm)})", f"[generator]({rel(f['script'], frm)})"]
        files += [f"[{pathlib.PurePosixPath(d).name}]({rel(d, frm)})" for d in f["data"]]
        out.append(f"Results: {res} · Files: {' · '.join(files)}\n")
        out.append(f"<details>\n<summary>Text description</summary>\n\n{f['alt']}\n\n</details>\n")
    return "\n".join(out).rstrip() + "\n"


