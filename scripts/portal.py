def build_results(results, papers, manifest, figures, ckpt):
    frm = "docs/results.md"
    fig_by_slug = {f["slug"]: f for f in figures}
    out = [GENERATED_NOTE.format(src="docs/registry/*.toml"),
           "# Curated result index\n",
           "Each result has a permanent identifier. Its entry gives the statement, the exact scope, the Lean "
           "declarations, a human-readable proof, the manuscript and the kind of evidence. Identifiers follow the "
           "mathematics, not the file layout: when a declaration moves, the identifier stays. Earlier, weaker "
           "declarations are listed under *Supersedes* so that the strongest theorem is easy to find. "
           "[Complete declaration directory](theorems.md) · [Manuscripts](../papers/README.md) · "
           "[Figures](figures.md) · [Registry format](registry/SCHEMA.md)\n",
           "**Kinds of evidence.** " + " ".join(f"*{STATUS[k]}*: {v}." for k, v in STATUS_HELP.items()) +
           f" Lean links point to the current files. *{CHECKPOINT_NAME}* links point to the same declaration at "
           f"commit [`{CHECKPOINT[:7]}`]({REPO}/tree/{CHECKPOINT}), for citation in manuscripts. "
           "Historical priority of these results is still under investigation; see the "
           "[literature comparisons](../notes/reviewers.md).\n"]
    by_topic = defaultdict(list)
    for r in results:
        by_topic[r["topic"]].append(r)
    out.append("## Summary\n")
    out.append("| ID | Result | Evidence | Paper |\n| --- | --- | --- | --- |")
    for topic in TOPICS:
        for r in by_topic.get(topic, []):
            p = paper_of(r["id"], papers)
            star = " ★" if r.get("principal") else ""
            out.append(f"| [{r['id']}](#{anchor(r['id'])}){star} | {r['title']} | {STATUS[r['status']]} | "
                       f"{p['number'] if p else ''} |")
    out.append("\n★ marks the principal results presented in the [README](../README.md).\n")
    for topic, title in TOPICS.items():
        items = by_topic.get(topic, [])
        if not items:
            continue
        out.append(f"## {title}\n")
        for r in items:
            out.append(f'<a id="{anchor(r["id"])}"></a>\n')
            out.append(f"### {r['id']} · {r['title']}\n")
            p = paper_of(r["id"], papers)
            meta = [f"**Evidence:** {STATUS[r['status']]}"]
            if p:
                meta.append(f"**Paper:** [{p['number']}. {p['title']}]({rel(p['dir'], frm)}) ({p['status']})")
            out.append(" · ".join(meta) + "\n")
            out.append(r["statement"].strip() + "\n")
            out.append("**Scope.** " + " ".join(r["scope"].split()) + "\n")
            lines = []
            decls = [resolve(n, manifest) for n in r.get("lean", [])]
            if decls:
                cur = " · ".join(decl_link(e, frm) for e in decls if e)
                lines.append(f"- **Lean:** {cur}")
                pins = [n for n in r.get("lean", []) if n in ckpt["lines"]]
                if pins:
                    links = " · ".join(
                        f"[`{n.rsplit('.', 1)[-1]}`]({REPO}/blob/{ckpt['commit']}/{ckpt['lines'][n][0]}#L{ckpt['lines'][n][1]})"
                        for n in pins)
                    lines.append(f"- **{CHECKPOINT_NAME}:** {links}")
                fq = ", ".join(f"`{n}`" for n in r.get("lean", []))
                lines.append(f"- **Fully qualified:** {fq}")
            lines.append("- **Proof:** " + " · ".join(path_link(t, frm) for t in r["proof"]))
            if r.get("inputs"):
                inputs = r["inputs"] if isinstance(r["inputs"], list) else [r["inputs"]]
                lines.append("- **External inputs:** " + " ".join(" ".join(x.split()) for x in inputs))
            if r.get("computation"):
                comp = r["computation"] if isinstance(r["computation"], list) else [r["computation"]]
                lines.append("- **Computation:** " + " · ".join(
                    path_link(c, frm) if (ROOT / c.partition("#")[0]).exists() else c for c in comp))
            if r.get("supersedes"):
                sup = []
                for s in r["supersedes"]:
                    if ID_RE.fullmatch(s):
                        sup.append(f"[{s}](#{anchor(s)})")
                    else:
                        e = resolve(s, manifest)
                        sup.append(decl_link(e, frm) if e else f"`{s}`")
                lines.append("- **Supersedes:** " + " · ".join(sup))
            if r.get("related"):
                lines.append("- **Related:** " + " · ".join(f"[{x}](#{anchor(x)})" for x in r["related"]))
            if r.get("figures"):
                lines.append("- **Figures:** " + " · ".join(
                    f"[{fig_by_slug[s]['title']}](figures.md#{s})" for s in r["figures"] if s in fig_by_slug))
            out.append("\n".join(lines) + "\n")
    out.append("## Manuscripts\n")
    out.append("Publication status is maintained in [papers/README.md](../papers/README.md). No manuscript has "
               "been peer reviewed or accepted.\n")
    for p in papers:
        ids = " · ".join(f"[{x}](#{anchor(x)})" for x in p["principal"])
        out.append(f"### {p['number']}. {p['title']}\n")
        out.append(f"**Status:** {p['status']} · **Results:** {ids} · [Directory]({rel(p['dir'], frm)})\n")
        out.append(" ".join(p["abstract"].split()) + "\n")
    return "\n".join(out).rstrip() + "\n"


