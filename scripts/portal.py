def derived(refresh_checkpoint: bool):
    manifest, entries = load_manifest()
    results, papers = load_registry()
    topics = load_topics()
    figures = load_figures()
    ckpt = checkpoint_lines(results, manifest, refresh_checkpoint)
    files = {
        "docs/results.md": build_results(results, papers, manifest, figures, ckpt),
        "docs/theorems.md": build_theorems(entries, topics, results),
        "docs/figures.md": build_figures(figures),
        "docs/data/checkpoint.json": json.dumps(ckpt, indent=1) + "\n",
    }
    for page in FIGURE_PAGES:
        path = ROOT / page
        if not path.exists():
            continue
        text = path.read_text()
        if page == "README.md":
            text = replace_block(text, "PAPERS", build_papers_block(papers))
        for f in figures:
            text = replace_block(text, f"FIGURE {f['slug']}", embedded_figure(f, page))
        files[page] = text
    return files


def cmd_build(_args):
    for path, text in derived(True).items():
        p = ROOT / path
        if not p.exists() or p.read_text() != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
            print(f"wrote {path}")
    return 0


