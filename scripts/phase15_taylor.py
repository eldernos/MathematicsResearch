"""Exact tests of affine Taylor denominators and the proportional-width budget."""

from fractions import Fraction
from math import gcd, lcm, prod

from phase15_arithmetic import factor_small, primes_upto


def odd(n):
    return n // (n & -n)


def taylor_rows(stop, shift):
    rows = [Fraction(0)]
    for k in range(1, stop + 1):
        rows.append(rows[-1] + Fraction(1 << shift, k << k))
    return rows


def exact_minimum(k, h):
    rows = taylor_rows(k + h, 0)
    q = odd(rows[k].denominator)
    b = lcm(*(odd(j) for j in range(k + 1, k + h + 1)))
    minimum = prod(p**e for p, e in factor_small(q).items() if b % p**e)
    # Enumerate the actual subgroup generated by increments in a common
    # cyclic group. Multiplication by a power of two preserves odd orders.
    modulus = lcm(q, b)
    scale = lcm(*(r.denominator for r in rows[k:]), modulus)
    dyadic = scale // odd(scale)
    residues = [int(r * dyadic * modulus) % modulus for r in rows[k:]]
    assert all((r * dyadic * modulus).denominator == 1 for r in rows[k:])
    reached = {residues[0]}
    for previous, current in zip(residues, residues[1:]):
        step = current - previous
        reached = {(x + j * step) % modulus for x in reached
                   for j in range(modulus // gcd(step, modulus))}
    assert len(reached) == b
    assert min(modulus // gcd(x, modulus) for x in reached) == minimum


def bounded_coefficients(k, h):
    rows = taylor_rows(k + h, k)
    primes = [p for p in primes_upto((k + h) // 2) if p > 2 and 2*p > k]
    coefficients = {k: 1}
    for p in primes:
        coefficients[2*p] = -4
        coefficients[2*p - 1] = coefficients.get(2*p - 1, 0) + 4
    assert sum(coefficients.values()) == 1
    x = sum(a * rows[j] for j, a in coefficients.items())
    assert odd(x.denominator) * prod(primes) == odd(rows[k].denominator)
    budget = sum(Fraction(abs(a), (j + 1) << (j-k)) for j, a in coefficients.items())
    assert budget <= Fraction(9, k+1)
    exponent = (x.denominator & -x.denominator).bit_length() - 1
    if primes and 2*primes[-1] - k - 1 > k.bit_length() - 1:
        assert exponent == 2*primes[-1] - k - 1
    window = -1
    while budget * (1 << (window + 9)) <= 1:
        window += 1
    return len(primes), sum(map(abs, coefficients.values())), exponent, window


if __name__ == "__main__":
    for k in range(1, 15):
        for h in range(5):
            exact_minimum(k, h)
    for k in (32, 64, 128, 256, 512, 2048):
        h = k // 2
        count, norm, exponent, window = bounded_coefficients(k, h)
        print(f"K={k} h={h} removed odd primes={count} norm={norm} "
              f"dyadic exponent={exponent} certified last shift={window if window >= 0 else 'none'}")
    print("All Taylor minimum and coefficient-budget checks passed.")
